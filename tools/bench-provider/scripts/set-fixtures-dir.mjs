// Writes server/fixtures-dir.generated.ts with the absolute path of test/fixtures/streams.
//
// The daemon evaluates the plugin bundle without __dirname/import.meta, so the provider cannot
// discover its own location at runtime. The path is therefore baked in at build time (this
// script runs as a `paseo-plugin.json` build step, in place, from the plugin directory).
// Override at runtime with BC_BENCH_FIXTURES.
import { existsSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const fixtures = resolve(root, "..", "..", "test", "fixtures", "streams");
if (!existsSync(fixtures) || !readdirSync(fixtures).some((f) => f.endsWith(".jsonl"))) {
  console.error(`No *.jsonl fixtures in ${fixtures}. Run: node test/fixtures/streams/generate.mts`);
  process.exit(1);
}
const target = join(root, "server", "fixtures-dir.generated.ts");
writeFileSync(
  target,
  `// Generated by scripts/set-fixtures-dir.mjs. Do not edit or commit.\nexport const FIXTURES_DIR = ${JSON.stringify(fixtures)};\n`,
);
console.log(`fixtures dir -> ${fixtures}`);
