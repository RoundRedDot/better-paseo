// Regenerates client/vendor/marked.js from the pinned marked release.
//
//   cd tools/vendor-marked && npm ci && npm run build
//
// Why (plan D5, D9): the host compiles the plugin client with esbuild only, and
// the Hermes in React Native 0.81.5 rejects every form of `class`. marked ships
// classes, static members and a private field, so it is lowered here with the
// class-only Babel plugins and committed. The lowered code is then minified
// with esbuild (whitespace, identifiers, syntax; target es2020, so nothing is
// lowered or raised past what Hermes takes), because the host does not minify
// plugin bundles and every byte ships to the device.
//
// Only the lexer ships: the client lexes Markdown and draws the tokens itself
// (`client/components/markdown/lex.ts`), so the parser, renderers, hooks and
// the `marked` instance would be dead weight in every catalog. The published
// ESM is one minified file whose top level builds a `Marked` instance, which
// keeps every class alive; tree-shaking it removes almost nothing. Its source
// map carries the original modules, so they are written out and bundled from
// an entry that exports `Lexer` alone, then lowered and minified as before.
// `marked.d.ts` re-exports every type but only `Lexer` as a value, so an
// import of anything else fails to type-check instead of at runtime.
//
// The output is deterministic for a given lockfile: same inputs, same bytes.
import { createRequire } from "node:module";
import { mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync, copyFileSync } from "node:fs";
import { tmpdir } from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const require = createRequire(import.meta.url);
const outDir = path.resolve(here, "../../client/vendor");

const babel = require("@babel/core");
const esbuild = require("esbuild");
const markedPkg = require("marked/package.json");
const markedDir = path.dirname(require.resolve("marked/package.json"));

/** The lexer and what it imports, from the original modules in marked's source map. */
function lexerSource() {
  const map = JSON.parse(readFileSync(path.join(markedDir, "lib/marked.esm.js.map"), "utf8"));
  if (!Array.isArray(map.sourcesContent) || map.sourcesContent.length !== map.sources.length) {
    throw new Error("marked's source map no longer carries its sources");
  }
  const work = mkdtempSync(path.join(tmpdir(), "vendor-marked-"));
  try {
    const lib = path.join(work, "lib");
    map.sources.forEach((source, index) => {
      const file = path.resolve(lib, source);
      mkdirSync(path.dirname(file), { recursive: true });
      writeFileSync(file, map.sourcesContent[index]);
    });
    const built = esbuild.buildSync({
      stdin: { contents: 'export { _Lexer as Lexer } from "./src/Lexer.ts";', resolveDir: work, loader: "ts" },
      bundle: true,
      format: "esm",
      // Classes stay classes here; Babel lowers them below.
      target: "es2022",
      treeShaking: true,
      write: false,
      logLevel: "silent",
    });
    return built.outputFiles[0].text;
  } finally {
    rmSync(work, { recursive: true, force: true });
  }
}

const source = lexerSource();

const plugin = (name) => require.resolve(`@babel/plugin-transform-${name}`);
const result = babel.transformSync(source, {
  babelrc: false,
  configFile: false,
  sourceType: "module",
  filename: "marked.esm.js",
  comments: false,
  // marked ships minified; keep it that way rather than pretty-print it.
  compact: true,
  sourceMaps: false,
  plugins: [
    plugin("class-static-block"),
    plugin("class-properties"),
    plugin("private-methods"),
    plugin("private-property-in-object"),
    plugin("classes"),
  ],
});
if (!result || typeof result.code !== "string") throw new Error("babel produced no output");

const minified = esbuild.transformSync(result.code, {
  loader: "js",
  format: "esm",
  target: "es2020",
  minify: true,
  legalComments: "none",
  charset: "utf8",
}).code;

// A leftover class or private name would fail on Hermes at load time, long
// after this script reported success, so the build re-parses its own output
// and refuses to write it. (A text search would trip on Babel's own
// "Cannot call a class as a function" message.)
const leftovers = [];
babel.traverse(babel.parseSync(minified, { sourceType: "module", configFile: false, babelrc: false }), {
  enter(nodePath) {
    if (/^Class|PrivateName|StaticBlock/.test(nodePath.node.type)) leftovers.push(nodePath.node.type);
  },
});
if (leftovers.length > 0) throw new Error(`class syntax survived lowering: ${leftovers.slice(0, 5).join(", ")}`);

const banner = [
  "/**",
  ` * marked v${markedPkg.version}, lowered for Hermes (no class syntax) and minified.`,
  " * GENERATED by tools/vendor-marked/build.mjs; do not edit. License: ./marked.LICENSE (MIT).",
  " * Upstream: https://github.com/markedjs/marked",
  " */",
  "// @ts-nocheck",
  "",
].join("\n");

writeFileSync(path.join(outDir, "marked.js"), `${banner}${minified}`);
// Every export the minified file has must be the lexer; anything else means
// marked's modules changed shape.
const exported = /export\s*\{([^}]*)\}/.exec(minified)?.[1].split(",").map((name) => name.trim().split(/\s+as\s+/).pop());
if (!exported || exported.length !== 1 || exported[0] !== "Lexer") throw new Error(`expected marked.js to export Lexer alone, got ${exported}`);

copyFileSync(path.join(markedDir, "lib/marked.d.ts"), path.join(outDir, "marked.types.d.ts"));
writeFileSync(
  path.join(outDir, "marked.d.ts"),
  [
    `// GENERATED by tools/vendor-marked/build.mjs; do not edit. marked v${markedPkg.version}.`,
    "// marked.js ships the lexer alone: every type, but only Lexer as a value.",
    'export type * from "./marked.types";',
    'export { Lexer } from "./marked.types";',
    "",
  ].join("\n"),
);
copyFileSync(path.join(markedDir, "LICENSE"), path.join(outDir, "marked.LICENSE"));

console.log(
  `marked ${markedPkg.version}: ${source.length} -> ${result.code.length} (lowered) -> ${minified.length} bytes (minified), babel ${babel.version}, esbuild ${esbuild.version}`,
);
